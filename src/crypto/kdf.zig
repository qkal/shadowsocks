const std = @import("std");

const Md5 = std.crypto.hash.Md5;
const HmacSha1 = std.crypto.auth.hmac.Hmac(std.crypto.hash.Sha1);
const HkdfSha1 = std.crypto.kdf.hkdf.Hkdf(HmacSha1);

pub fn deriveClassicMasterKey(password: []const u8, out: []u8) !void {
    if (out.len == 0) return;

    var previous: [Md5.digest_length]u8 = undefined;
    var offset: usize = 0;
    var have_previous = false;

    while (offset < out.len) {
        var hash = Md5.init(.{});
        if (have_previous) hash.update(&previous);
        hash.update(password);
        hash.final(&previous);

        const take = @min(out.len - offset, previous.len);
        @memcpy(out[offset..][0..take], previous[0..take]);
        offset += take;
        have_previous = true;
    }
}

pub fn deriveSessionSubkey(master_key: []const u8, salt: []const u8, out: []u8) !void {
    if (out.len == 0) return;

    const prk = HkdfSha1.extract(salt, master_key);
    HkdfSha1.expand(out, "ss-subkey", prk);
}

test "classic EVP bytes-to-key derives the aes-256-gcm master key" {
    var out: [32]u8 = undefined;
    try deriveClassicMasterKey("test-password", out[0..]);

    const expected = [_]u8{
        0xdf, 0xb4, 0x50, 0xef, 0xdd, 0xbb, 0x53, 0x87,
        0x19, 0x7c, 0x84, 0x46, 0x06, 0x23, 0x67, 0x5b,
        0x69, 0xf2, 0xce, 0xbc, 0xd8, 0xef, 0x52, 0x0a,
        0x3d, 0xfd, 0xde, 0xf7, 0xc3, 0xd5, 0x40, 0xb2,
    };

    try std.testing.expectEqualSlices(u8, &expected, out[0..]);
}

test "classic HKDF-SHA1 derives the session subkey" {
    const master = [_]u8{
        0xdf, 0xb4, 0x50, 0xef, 0xdd, 0xbb, 0x53, 0x87,
        0x19, 0x7c, 0x84, 0x46, 0x06, 0x23, 0x67, 0x5b,
        0x69, 0xf2, 0xce, 0xbc, 0xd8, 0xef, 0x52, 0x0a,
        0x3d, 0xfd, 0xde, 0xf7, 0xc3, 0xd5, 0x40, 0xb2,
    };
    const salt = [_]u8{
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
        0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f,
        0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
        0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f,
    };
    var out: [32]u8 = undefined;
    try deriveSessionSubkey(master[0..], salt[0..], out[0..]);

    const expected = [_]u8{
        0x7b, 0x6c, 0xa1, 0x2d, 0x45, 0xef, 0x79, 0x46,
        0x74, 0x32, 0x71, 0x7a, 0xaa, 0x6a, 0x6a, 0xe6,
        0xe1, 0xdd, 0x04, 0x6a, 0x50, 0x5f, 0xb2, 0xeb,
        0xaa, 0xac, 0x60, 0x22, 0x10, 0x91, 0x95, 0x95,
    };

    try std.testing.expectEqualSlices(u8, &expected, out[0..]);
}
